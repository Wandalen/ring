#!/usr/bin/env python3
"""Build index.html: compile deck_engine/ to wasm32, then inline it and src/ into src/deck.html.

    python3 docs/presentation/build.py                 # index.html, a standalone page
    python3 docs/presentation/build.py --fragment OUT  # no doctype/head, for hosts that add their own
"""
import base64
import os
import pathlib
import subprocess
import sys

HERE = pathlib.Path(__file__).resolve().parent
TARGET = HERE / 'deck_engine' / 'target'

# Its own target dir: the release profile here is size-tuned, and a shared target dir with path
# deps into the workspace can leave artifacts that break the workspace build.
subprocess.run(
    ['cargo', 'build', '-q', '--release', '--target', 'wasm32-unknown-unknown',
     '--manifest-path', str(HERE / 'deck_engine' / 'Cargo.toml')],
    check=True, env={**os.environ, 'CARGO_TARGET_DIR': str(TARGET)},
)
wasm = (TARGET / 'wasm32-unknown-unknown' / 'release' / 'deck_engine.wasm').read_bytes()

page = (HERE / 'src' / 'deck.html').read_text()
for slot, name in [('/*__ENGINE_JS__*/', 'mirror.js'), ('/*__APP_JS__*/', 'app.js')]:
    assert slot in page, slot
    page = page.replace(slot, (HERE / 'src' / name).read_text())
assert '__WASM_B64__' in page
page = page.replace('__WASM_B64__', base64.b64encode(wasm).decode())

if '--fragment' in sys.argv:
    out = pathlib.Path(sys.argv[sys.argv.index('--fragment') + 1])
else:
    out = HERE / 'index.html'
    page = ('<!doctype html>\n<!-- Generated by build.py from src/ and deck_engine/. Do not edit by hand. -->\n'
            '<html lang="uk">\n<meta charset="utf-8">\n'
            '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">\n' + page)
out.write_text(page)
print(f'{out.name}: {len(page)} bytes, wasm {len(wasm)} bytes')
